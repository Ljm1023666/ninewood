import re
STOP = set("的了吗呢啊请要想找帮和与你我是他在有上中下大小一个也都就还这那我们被把被让向从对于及或与跟")
def segment_title(title):
    segs = set()
    for run in re.findall(r"[\u4e00-\u9fa5]+", title):
        if len(run) >= 2 and run not in STOP:
            segs.add(run)
        if len(run) > 2:
            for length in (2, 3, 4):
                for i in range(len(run) - length + 1):
                    frag = run[i:i+length]
                    if frag not in STOP:
                        segs.add(frag)
    return segs
def title_core_hits(sample_n=20):
    checked = demands[:sample_n]
    ok = 0
    for dm in checked:
        segs = segment_title(dm["title"])
        tags = set(dm["tags"])
        hit = any(any(seg in tg or tg in seg for tg in tags) for seg in segs) or \
              any(t in dm["title"] for t in tags)
        if hit: ok += 1
    return ok, sample_n

